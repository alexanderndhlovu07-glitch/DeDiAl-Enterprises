import assert from 'node:assert/strict';
import {chromium} from 'playwright';
import {spawn, spawnSync} from 'node:child_process';
import {mkdtemp, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';

const temp = await mkdtemp(path.join(tmpdir(), 'dedial-browser-'));
const db = path.join(temp, 'accounts.sqlite3');
const python = process.env.PYTHON_BIN || 'python3';
const server = spawn(python, ['tools/dev.py', '--db', db, '--platform-port','4273','--landing-port','4274'], {stdio:'pipe'});
let browser;
const errors = [];
try {
  for(let i=0;i<100;i++) {
    try {if((await fetch('http://127.0.0.1:4273/api/v1/auth/session')).ok) break;} catch {}
    if(i===99) throw new Error('Test server did not start.');
    await new Promise(resolve=>setTimeout(resolve,100));
  }
  browser = await chromium.launch({headless:true, ...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{})});
  const context = await browser.newContext({viewport:{width:1440,height:1000}, reducedMotion:'reduce'});
  const page = await context.newPage();
  page.setDefaultTimeout(12000);
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400)errors.push(`${r.status()} ${r.url()}`);});
  page.on('requestfailed',r=>{if(!r.failure()?.errorText.includes('ERR_ABORTED'))errors.push(`${r.failure()?.errorText} ${r.url()}`);});
  await page.goto('http://127.0.0.1:4274/');
  await page.locator('#hero-title').waitFor();
  assert.match(await page.locator('#hero-title').innerText(),/Your world/);
  await page.locator('[data-lex-example="book"]').click();
  assert.ok((await page.locator('#lex-response').innerText()).length>20);
  assert.match(await page.locator('[data-platform-link]').first().getAttribute('href'), /:4273/);
  await page.setViewportSize({width:390,height:844});
  await page.locator('#menu-toggle').click();
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'),'true');
  await page.locator('#menu-toggle').click();
  if(process.env.RECOVERY_SCREENSHOTS) await page.screenshot({path:path.join(process.env.RECOVERY_SCREENSHOTS,'landing-mobile.png')});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto('http://127.0.0.1:4273/#signup');
  await page.locator('#auth-name').fill('Recovery Test');
  await page.locator('#auth-email').fill('recovery@example.invalid');
  await page.locator('#auth-password').fill('Recovery-local-password-42');
  await page.locator('#auth-form button[type=submit]').click();
  await page.locator('.hero h1').waitFor();
  if(process.env.RECOVERY_SCREENSHOTS) await page.screenshot({path:path.join(process.env.RECOVERY_SCREENSHOTS,'platform-home.png')});
  await page.locator('.nav a[href="#book"]').click();
  await page.locator('[data-action="book"]').first().click();
  await page.locator('[data-action="slot"]').first().click();
  await page.locator('#booking-form [name="policy"]').check();
  await page.locator('#confirm-booking').click();
  await page.getByRole('link',{name:'View my activity'}).click();
  await page.locator('[data-action="cancel-booking"]').waitFor();
  await page.reload();
  await page.locator('[data-action="cancel-booking"]').click();
  await page.locator('[data-action="confirm-cancel"]').click();
  await page.getByText('cancelled',{exact:true}).waitFor();
  await page.locator('.nav a[href="#procure"]').click();
  await page.locator('[name="product"]').fill('Recovery headphones');
  await page.locator('#procurement-form button[type="submit"], #procurement-form button').click();
  await page.locator('[data-action="review-quote"]').first().click();
  await page.locator('#quote-form input[type=checkbox]').check();
  await page.locator('#quote-form button').click();
  await page.locator('[data-action="pay"]').click();
  await page.locator('[data-action="confirm-pay"]').click();
  await page.getByText('Demo payment simulated',{exact:true}).waitFor();
  await page.goto('http://127.0.0.1:4273/#assistant');
  await page.locator('[name="prompt"]').fill('Track my activity');
  await page.locator('.send-button').click();
  await page.locator('.chat-message.assistant').waitFor();
  assert.match(await page.locator('.chat-message.assistant').innerText(), /1 sample booking/);
  await page.goto('http://127.0.0.1:4273/#admin');
  await page.getByText('Access requires approval.',{exact:true}).waitFor();
  const role = spawnSync(python,['tools/dev.py','--db',db,'--set-role','recovery@example.invalid','operator']);
  assert.equal(role.status,0,role.stderr?.toString());
  await page.reload();
  await page.locator('[data-action="admin-tab"]').first().waitFor();
  await page.goto('http://127.0.0.1:4273/#business');
  await page.locator('[data-action="portal-tab"]').first().waitFor();
  await page.goto('http://127.0.0.1:4273/#architecture');
  await page.getByText('The delivery roadmap',{exact:true}).waitFor();
  await page.goto('http://127.0.0.1:4273/#account');
  await page.locator('[data-action="logout"]').click();
  await page.locator('#auth-email').waitFor();
  await page.locator('#auth-email').fill('recovery@example.invalid');
  await page.locator('#auth-password').fill('Recovery-local-password-42');
  await page.locator('#auth-form button[type=submit]').click();
  await page.locator('.hero h1').waitFor();
  await page.setViewportSize({width:390,height:844});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
  await page.goto('http://127.0.0.1:4273/#activity');
  await page.getByText('Recovery headphones',{exact:true}).waitFor();
  // A different local account gets a separate browser-state namespace.
  await page.goto('http://127.0.0.1:4273/#account');
  await page.locator('[data-action="logout"]').click();
  await page.locator('a[href="#signup"]').last().click();
  await page.locator('#auth-name').fill('Second Account');
  await page.locator('#auth-email').fill('second@example.invalid');
  await page.locator('#auth-password').fill('Another-local-password-42');
  await page.locator('#auth-form button[type=submit]').click();
  await page.locator('.hero h1').waitFor();
  await page.goto('http://127.0.0.1:4273/#activity');
  await page.locator('.empty').waitFor();
  assert.equal(await page.getByText('Recovery headphones',{exact:true}).count(),0);
  assert.deepEqual(errors,[]);
  console.log('PASS: landing interactions/mobile navigation, signup/login/logout, sessions, booking/cancellation, sourcing/quote/payment, Lex, role gates, business/admin screens, persistence, account state isolation, mobile layout, and no failed resources or browser exceptions.');
} finally {
  if(browser) await browser.close();
  server.kill('SIGINT');
  await new Promise(resolve=>{if(server.exitCode!==null)resolve();else server.once('exit',resolve);});
  await rm(temp,{recursive:true,force:true});
}
